import pg from 'pg';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Import a verified snapshot, never a live SQLite file. No source writes.
const snapshotPath = process.argv[2];
if (!snapshotPath || !process.env.DATABASE_URL)
  throw new Error('Informe backup e DATABASE_URL.');
const manifest = JSON.parse(
  readFileSync(snapshotPath + '.manifest.json', 'utf8'),
);
if (
  createHash('sha256').update(readFileSync(snapshotPath)).digest('hex') !==
  manifest.sha256
)
  throw new Error('Backup não corresponde ao manifesto.');
const sqlite = new DatabaseSync(snapshotPath, { readOnly: true });
const names = [
  'profiles',
  'entries',
  'financial_users',
  'salary_defaults',
  'monthly_cycles',
  'categories',
  'recurrence_templates',
  'ledger_entries',
  'recurrence_values',
  'notification_preferences',
  'notification_jobs',
];
const quote = (s) => '"' + s.replaceAll('"', '""') + '"';
const connection = new URL(process.env.DATABASE_URL);
connection.searchParams.delete('sslmode');
const client = new pg.Client({
  connectionString: connection.toString(),
  ssl: {
    rejectUnauthorized: true,
    ...(process.env.PGSSLROOTCERT
      ? { ca: readFileSync(process.env.PGSSLROOTCERT, 'utf8') }
      : {}),
  },
  connectionTimeoutMillis: 15000,
});
const digest = (rows) =>
  createHash('sha256').update(JSON.stringify(rows)).digest('hex');
let transaction = false;
try {
  await client.connect();
  await client.query('BEGIN');
  transaction = true;
  await client.query('SELECT pg_advisory_xact_lock(921604)');
  const existing = await client.query(
    "SELECT 1 FROM pg_namespace WHERE nspname='cenaplanner'",
  );
  if (existing.rowCount)
    throw Object.assign(
      new Error(
        'Destino já existe; importação cancelada para preservar dados.',
      ),
      { code: 'DESTINATION_EXISTS' },
    );
  const users = sqlite.prepare('SELECT user_id FROM financial_users').all();
  for (const { user_id } of users) {
    const result = await client.query(
      'SELECT 1 FROM auth.users WHERE id=$1::uuid',
      [user_id],
    );
    if (!result.rowCount)
      throw Object.assign(
        new Error('Usuário de origem ausente na autenticação de destino.'),
        { code: 'AUTH_USER_MISSING' },
      );
  }
  await client.query('CREATE SCHEMA cenaplanner');
  await client.query(
    'REVOKE ALL ON SCHEMA cenaplanner FROM PUBLIC, anon, authenticated',
  );
  const totals = {};
  for (const name of names) {
    const columns = sqlite.prepare(`PRAGMA table_info(${quote(name)})`).all();
    if (!columns.length)
      throw Object.assign(new Error('Tabela ausente no backup.'), {
        code: 'SOURCE_TABLE_MISSING',
      });
    const definitions = columns.map((c) => {
      let type =
        c.type.toUpperCase() === 'INTEGER'
          ? 'bigint'
          : c.type.toUpperCase() === 'REAL'
            ? 'double precision'
            : 'text';
      if (c.pk && type === 'bigint')
        type += ' GENERATED BY DEFAULT AS IDENTITY';
      return `${quote(c.name)} ${type}${c.pk ? ' PRIMARY KEY' : ''}${c.notnull ? ' NOT NULL' : ''}${c.dflt_value !== null && !c.pk ? ' DEFAULT ' + c.dflt_value : ''}`;
    });
    await client.query(
      `CREATE TABLE cenaplanner.${quote(name)} (${definitions.join(',')})`,
    );
    await client.query(
      `ALTER TABLE cenaplanner.${quote(name)} ENABLE ROW LEVEL SECURITY`,
    );
    await client.query(
      `REVOKE ALL ON cenaplanner.${quote(name)} FROM PUBLIC, anon, authenticated`,
    );
    const cols = columns.map((c) => c.name);
    const primary = columns
      .filter((c) => c.pk)
      .sort((a, b) => a.pk - b.pk)
      .map((c) => c.name);
    if (!primary.length) throw new Error('Chave primária necessária.');
    const order = primary.map(quote).join(',');
    const rows = sqlite
      .prepare(`SELECT * FROM ${quote(name)} ORDER BY ${order}`)
      .all();
    for (let offset = 0; offset < rows.length; offset += 100) {
      const batch = rows.slice(offset, offset + 100),
        values = [];
      const tuples = batch.map(
        (row) =>
          '(' +
          cols
            .map((col) => {
              values.push(row[col]);
              return '$' + values.length;
            })
            .join(',') +
          ')',
      );
      await client.query(
        `INSERT INTO cenaplanner.${quote(name)} (${cols.map(quote).join(',')}) VALUES ${tuples.join(',')}`,
        values,
      );
    }
    for (const index of sqlite
      .prepare(`PRAGMA index_list(${quote(name)})`)
      .all()) {
      if (index.origin === 'pk') continue;
      if (index.partial)
        throw new Error('Índice parcial exige tradução explícita.');
      const indexCols = sqlite
        .prepare(`PRAGMA index_info(${quote(index.name)})`)
        .all();
      if (indexCols.some((c) => !c.name))
        throw new Error('Índice de expressão exige tradução explícita.');
      await client.query(
        `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quote(name + '_' + index.seq + '_idx')} ON cenaplanner.${quote(name)} (${indexCols.map((c) => quote(c.name)).join(',')})`,
      );
    }
    for (const c of columns.filter(
      (c) => c.pk && c.type.toUpperCase() === 'INTEGER',
    )) {
      await client.query(
        `SELECT setval(pg_get_serial_sequence($1,$2),COALESCE((SELECT max(${quote(c.name)}) FROM cenaplanner.${quote(name)}),1),(SELECT count(*)>0 FROM cenaplanner.${quote(name)}))`,
        ['cenaplanner.' + name, c.name],
      );
    }
    const copied = (
      await client.query(
        `SELECT * FROM cenaplanner.${quote(name)} ORDER BY ${order}`,
      )
    ).rows;
    const normalized = copied.map((row) =>
      cols.map((col) => {
        const c = columns.find((c) => c.name === col);
        return row[col] !== null &&
          ['INTEGER', 'REAL'].includes(c.type.toUpperCase())
          ? Number(row[col])
          : row[col];
      }),
    );
    if (
      digest(rows.map((row) => cols.map((col) => row[col]))) !==
      digest(normalized)
    )
      throw Object.assign(new Error('Verificação divergente.'), {
        code: 'DATA_MISMATCH',
      });
    totals[name] = rows.length;
  }
  await client.query(
    'REVOKE ALL ON ALL SEQUENCES IN SCHEMA cenaplanner FROM PUBLIC, anon, authenticated',
  );
  await client.query('COMMIT');
  transaction = false;
  console.log(
    JSON.stringify({ migrated: true, verified: true, tables: totals }),
  );
} catch (error) {
  if (transaction) await client.query('ROLLBACK').catch(() => {});
  console.error(
    JSON.stringify({ migrated: false, code: error.code || 'MIGRATION_FAILED' }),
  );
  process.exitCode = 1;
} finally {
  sqlite.close();
  await client.end().catch(() => {});
}
